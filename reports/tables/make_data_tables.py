def split_d1(body: str) -> dict:
    """D1's two halves, one file each.

    One table was doing two jobs: WHAT WAS COLLECTED (a row per stream) and WHAT THE INSTRUMENT
    IS LIKE (tick, spread, volumes, order sizes). It absorbed that for three source rows, at
    4.2pt over its float box. Adding the trade row on 2026-08-09 took the overflow to 98.9pt,
    about 3.5cm, which no amount of vertical spacing recovers. Measured: sources alone overflow
    by nothing at all, with every cell at full length and row spacing untouched.

    d1_sources.tex is still written, because the two halves read as one exhibit outside the
    dissertation. Same reasoning as `split_d3`.
    """
    hdr = "% Auto-generated by reports/tables/make_data_tables.py. Do not edit.\n"
    col = r"\newcolumntype{R}[1]{>{\raggedright\arraybackslash}p{#1}}"
    L = body.split("\n")
    i = next(k for k, l in enumerate(L) if l.startswith(r"\multicolumn{6}{@{}l}{\emph{Instrument"))
    assert L[i - 1] == r"\midrule", L[i - 1]

    # L[0] is already the generator header; prepending hdr to it printed the line twice.
    body_lines = L[1:] if L[0].startswith("% Auto-generated") else L[:]
    j = i - 1 - (1 if L[0].startswith("% Auto-generated") else 0)
    sources = hdr + "\n".join(body_lines[:j] + [r"\bottomrule", r"\end{tabular}"]) + "\n"
    instrument = hdr + "\n".join(
        [col, r"\begin{tabular}{@{}R{2.2cm} R{3.0cm} R{3.1cm} R{2.0cm} R{2.0cm} R{1.9cm}@{}}",
         r"\toprule"] + L[i:]) + "\n"
    assert r"\bottomrule" in instrument and "tick size" in instrument
    assert "Book snapshots" in sources and "tick size" not in sources
    # `instrument` above is the LEGACY six-column half, still asserted so the combined
    # d1_sources.tex stays coherent for readers outside the dissertation. The dissertation gets
    # the rebuilt symbol/quantity/value table instead. See table_d1b_instrument's docstring.
    return {"d1a_sources": sources, "d1b_instrument": table_d1b_instrument()}


def split_d3(body: str) -> dict:
    """D3's three panels, one file each.

    The three panels stack to 820pt against 703pt of page height, so they cannot be one
    float; and each belongs beside a different paragraph of section 3.4, so no paragraph
    refers forward. d3_partitions.tex is still written, because the panels read as one
    exhibit outside the dissertation.
    """
    parts = body.split(r"\begin{tabular}")
    panels = [r"\begin{tabular}" + s.split(r"\end{tabular}")[0] + "\\end{tabular}\n"
              for s in parts[1:]]
    assert len(panels) == 3, len(panels)
    hdr = "% Auto-generated by reports/tables/make_data_tables.py. Do not edit.\n"
    return {"d3a_versions": hdr + panels[0],     # section 3.4, paragraph 1
            "d3b_seedsets": hdr + panels[1],     # section 3.4, paragraph 3
            "d3c_december": hdr + panels[2]}     # section 3.4, paragraph 2


def table_d2b() -> str:
    """The per-order record's processing steps, and what was checked at each.

    The parallel to `table_d2`, which does the same for the snapshot record. Three rows only,
    and deliberately so: Table 3.1 already carries the SOURCES (what each stream holds, the
    missing clock, the identifier match, 31 of 31 days, 5,355,301 states) and Table 3.5 carries
    the DIVISION into fitting and holdout hours. Restating either here would be the exhibit-scale
    version of the mistake this chapter has already been caught on twice. What sits nowhere else
    is the processing between them, which is what these three rows hold.
    """
    P = M["perorder_pipeline"]
    rows = [
        (r"warming up the replay",
         (f"the first {n(P['warmup_events'])} changes are applied without being recorded. The replay "
          r"starts from an empty book, and learns of an order only when that order changes, so it "
          r"holds too little volume until the orders present at the start have gone"),
         (f"recording begins {P['grid_start_minutes_into_1_dec']:.1f} minutes into 1 December, leaving hour 0 "
          f"of that day short of book data and outside the regime split, the "
          f"{'only such hour' if P['hours_unlabelled'] == 1 else 'only such hours'} of the month's "
          f"{n(P['hours_expected'])}")),
        (r"removing phantom orders",
         (f"{n(P['phantom_orders_removed'])} orders across the month are removed before they appear. In the "
          r"sub-second ordering of the two streams, a cancellation can be recorded before the order "
          r"it cancels"),
         (r"audited 4 July 2026. One rule, applied uniformly across the month. Without it, such "
          r"orders rest in the book indefinitely")),
        (r"verifying the reconstruction",
         (r"a second, independent pass over the same raw records, advancing the book event by event, "
          r"and sampling it back to the same half-second points"),
         (f"the two methods agree exactly, across all {n(P['n_grid_rows'])} states")),
    ]
    # Columns widened 2026-08-09 to use the full 16cm text width. Table 3.4 sits at the top
    # of the page that also carries ALL of section 3.4's prose; every wrapped line it saves
    # is a line that paragraph needs. See (Y17).
    out = [r"% Auto-generated by reports/tables/make_data_tables.py. Do not edit.",
           r"\begin{tabular}{@{}p{2.4cm} p{7.9cm} p{5.5cm}@{}}", r"\toprule",
           r"step & what it produced & what was checked \\", r"\midrule"]
    out += [" & ".join(c) + r" \\" for c in rows]
    out += [r"\bottomrule", r"\end{tabular}"]
    return "\n".join(out) + "\n"


def main() -> None:
    d1, d3 = table_d1(), table_d3()
    outputs = {"d1_sources": d1, "d2_pipeline": table_d2(),
               "d2b_perorder": table_d2b(), "d3_partitions": d3}
    outputs.update(split_d1(d1))
    outputs.update(split_d3(d3))
    for name, body in outputs.items():
        p = HERE / f"{name}.tex"
        p.write_text(body)
        print(f"wrote {p}  ({len(body.splitlines())} lines)")


if __name__ == "__main__":
    main()
