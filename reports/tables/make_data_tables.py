def esc(s: str) -> str:
    return s.replace("%", r"\%").replace("&", r"\&").replace("_", r"\_")


def n(x: float, dp: int = 0) -> str:
    """Thousands-separated fixed-point, so a table never invents precision."""
    return f"{x:,.{dp}f}"


