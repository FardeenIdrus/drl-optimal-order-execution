def table_d1b_instrument() -> str:
    """Table 3.1: the instrument's measured properties, one symbol per quantity.

    REBUILT 2026-08-13 on Carlo's comment: "this can stay as a table if you just introduce some
    mathematical notation (which you need later anyways) for volume, order sizes etc and turn it
    into a simple variable - value table." Six columns of phrases became three of symbol,
    quantity and value.

    THREE THINGS LEFT, each for a stated reason.
      * Both order-size rows. They are experimental design, not properties of the instrument,
        no prose in chapter 3 uses the ladder, and `m2_tracks.tex` already carries it with the
        environment and cadence that make it readable. Methodology owns Q.
      * "(first 7-day sample: 94.3%)". A measurement taken before the month was processed is an
        intermediate step of development, which his general comment rules out.
      * The caption's volume sentence, which restated rows of the table beneath it.

    ONE THING ARRIVED. December's median daily volume, 30,754 BTC, which was reachable only
    through the caption. The mean and the median are needed on BOTH periods because the study
    expresses order sizes as a percentage of daily volume against two different denominators;
    printing either as "%ADV" without saying which average is a factual error. The subscripts
    exist for that reason and are not decoration.

    THE MID IS A MEDIAN OF MEDIANS. `tick_class_measure.py:188-189` takes np.median over the 31
    per-day medians, not over the 5,355,301 observations, and the relative tick follows from it
    ($1.00 / 88,417.50 reproduces the reported figure exactly). The old panel header said
    "measured across all 31 days and 5,355,301 half-second samples", which implied pooled. The
    note below says what was actually computed.

    NO NUMBER IS TYPED. The tick was the one exception in the old table (a literal "\\$1.00" at
    what was line 112); it now reads `tick_values_seen`, which the measurement asserts is a
    single value across all 31 days.
    """
    sp = TC["spread"]["full_month"]
    ticks_seen = TC["tick_values_seen"]
    assert TC["tick_constant_across_days"] and len(ticks_seen) == 1, ticks_seen
    tick = float(ticks_seen[0])

    panel_a = [
        (r"$\delta$", "tick size", rf"\${tick:,.2f}"),
        (r"$\tilde{p}$", "median mid-quote", r"\$" + n(sp["median_mid"], 2)),
        # Typeset as the prose does. ":.3e" printed "1.131e-05", a machine literal in the one
        # table a marker opens to check the prose's $1.13\times10^{-5}$ against.
        (r"$\delta/\tilde{p}$", "relative tick",
         f"${sp['relative_tick'] * 1e5:.2f}" + r"\times10^{-5}$"),
        (r"$\bar{s}$", "mean spread",
         f"{sp['mean_spread_ticks']:.3f} ticks, {sp['mean_spread_bps']:.4f} bps"),
        (r"$P(s=\delta)$", "probability the spread is one tick",
         f"{100 * sp['p_spread_1_tick']:.1f}\\%"),
    ]
    panel_b = [
        (r"$\bar{V}_{2\mathrm{y}}$",
         f"average daily volume, {ADV['window']['start']} to {ADV['window']['end']}",
         f"{n(ADV['adv_btc'], 0)} BTC"),
        (r"$\tilde{V}_{2\mathrm{y}}$", "median daily volume, same span",
         f"{n(ADV['median_daily_btc'], 0)} BTC, range {n(ADV['min_daily_btc'], 0)} to "
         f"{n(ADV['max_daily_btc'], 0)}"),
        (r"$\bar{V}_{\mathrm{Dec}}$", "average daily volume, December 2025",
         f"{n(TV['mean_daily_btc'], 0)} BTC"),
        (r"$\tilde{V}_{\mathrm{Dec}}$", "median daily volume, December 2025",
         f"{n(TV['median_daily_btc'], 0)} BTC"),
    ]

    # 0.90, not 0.94: the two internal column boundaries cost 4\tabcolsep, and the note is set
    # to the same total so it cannot run past the rules above it. Same arithmetic as
    # make_methodology_appendix_tables.py.
    note = r"\multicolumn{3}{@{}p{\dimexpr0.90\linewidth+4\tabcolsep}@{}}"
    L = [r"% Auto-generated by reports/tables/make_data_tables.py. Do not edit.",
         r"\begin{tabular}{@{}p{0.10\linewidth}p{0.45\linewidth}p{0.35\linewidth}@{}}",
         r"\toprule",
         r"\multicolumn{3}{@{}l}{\emph{Panel A. Price and spread, December 2025}} \\",
         r"\midrule"]
    for s, q, v in panel_a:
        L.append(f"{s} & {q} & {v} \\\\")
    L += [note + r"{\footnotesize Measured on the reconstructed half-second book, "
          + n(sp["n_samples"]) + r" observations. The mid-quote is the median across the "
          + f"month's {sp['n_days']} daily medians, and the relative tick follows from it."
          + r"} \\",
          r"\addlinespace[0.6em]", r"\midrule",
          r"\multicolumn{3}{@{}l}{\emph{Panel B. Traded volume}} \\",
          r"\midrule"]
    for s, q, v in panel_b:
        L.append(f"{s} & {q} & {v} \\\\")
    L += [r"\bottomrule", r"\end{tabular}"]
    return "\n".join(L) + "\n"


